import { parseCSharp, CSharpParseError } from "./csharp/parser";
import { Renderer } from "./layout";
import { resolveOptions, type PartialOptions } from "./options";
import { offsetToLine } from "./trivia";
import type { FileModel, Hazard } from "./types";
import { parseTypeScript, TsParseError } from "./typescript/parser";

export type Language = "csharp" | "typescript";

export interface SortResult {
  text: string;
  changed: boolean;
  hazards: Hazard[];
  /** Set when the whole file was left untouched on purpose. */
  skippedReason?: string;
}

const TS_EXTENSIONS = [".ts", ".tsx", ".mts", ".cts", ".js", ".jsx", ".mjs", ".cjs"];
export const SUPPORTED_EXTENSIONS = [".cs", ...TS_EXTENSIONS];

export function languageFor(fileName: string): Language | null {
  const lower = fileName.toLowerCase();
  if (lower.endsWith(".cs")) return "csharp";
  if (TS_EXTENSIONS.some(e => lower.endsWith(e))) return "typescript";
  return null;
}

/**
 * Pure function: text in, text out. No VS Code dependency, so it is what the
 * tests exercise directly.
 */
export function sortText(text: string, fileName: string, partial: PartialOptions = {}): SortResult {
  const opts = resolveOptions(partial);
  const lang = languageFor(fileName);
  const unchanged = (reason: string, hazard?: Omit<Hazard, "line">): SortResult => {
    const hazards = hazard ? withLines(text, [hazard]) : [];
    return { changed: false, hazards, skippedReason: reason, text };
  };
  if (!lang) return unchanged("unsupported file type");

  if (/sort-code-disable-file/.test(text)) {
    return unchanged("disabled by comment", {
      code: "disabled-by-comment",
      message: "Sorting disabled for this file (sort-code-disable-file).",
      offset: text.indexOf("sort-code-disable-file"),
      severity: "info"
    });
  }
  const head = text.slice(0, 2000);
  if (/<auto-generated|@generated\b/i.test(head)) {
    return unchanged("generated file", {
      code: "generated-file",
      message: "Generated file: not sorted.",
      offset: 0,
      severity: "info"
    });
  }

  let model: FileModel;
  try {
    model = lang === "csharp" ? parseCSharp(text, opts) : parseTypeScript(text, fileName, opts);
  } catch (e) {
    if (e instanceof CSharpParseError || e instanceof TsParseError) {
      return unchanged("syntax error", {
        code: "syntax-error",
        message: `Not sorted: the file does not parse cleanly (${e.message}). Fix the syntax error and save again.`,
        offset: e.offset,
        severity: "warning"
      });
    }
    throw e;
  }

  const hazards = [...model.hazards];
  const out = new Renderer(text, opts, hazards).renderContainer(model.root);
  hazards.sort((a, b) => a.offset - b.offset);
  return { changed: out !== text, hazards: withLines(text, hazards), text: out };
}

function withLines(text: string, hazards: Omit<Hazard, "line">[]): Hazard[] {
  return hazards.map(h => ({ ...h, line: offsetToLine(text, h.offset) }));
}
