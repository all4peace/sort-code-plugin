/** Focused, readable checks of individual rules — the "spec" in executable form. */
import assert from "node:assert/strict";
import { describe, test } from "node:test";

import { minimalEdit } from "../src/core";
import { sortText } from "../src/core/sortText";

const names = (code: string, re: RegExp): string[] => [...code.matchAll(re)].map(m => m[1]);
const csMethods = (code: string): string[] => names(code, /void (\w+)\(/g);

describe("C# ordering rules", () => {
  const cls = `class C
{
    private void PrivateB() { }
    internal void InternalA() { }
    public void PublicZ() { }
    protected void ProtectedM() { }
    public void PublicA() { }
    public static void StaticZ() { }
}
`;

  test("public → internal → protected → private, alphabetical, static first", () => {
    assert.deepEqual(csMethods(sortText(cls, "a.cs").text), ["StaticZ", "PublicA", "PublicZ", "InternalA", "ProtectedM", "PrivateB"]);
  });

  test("staticFirst: false sorts statics with instance members", () => {
    assert.deepEqual(csMethods(sortText(cls, "a.cs", { staticFirst: false }).text), ["PublicA", "PublicZ", "StaticZ", "InternalA", "ProtectedM", "PrivateB"]);
  });

  test("custom access order", () => {
    const out = sortText(cls, "a.cs", { accessOrder: ["private", "protected", "internal", "public"] }).text;
    assert.deepEqual(csMethods(out), ["PrivateB", "ProtectedM", "InternalA", "StaticZ", "PublicA", "PublicZ"]);
  });

  test("custom member kind order (methods before properties)", () => {
    const src = "class C\n{\n    public int P { get; set; }\n    public void M() { }\n}\n";
    const out = sortText(src, "a.cs", { csharp: { memberOrder: ["method", "property"] } }).text;
    assert.ok(out.indexOf("void M") < out.indexOf("int P"));
  });

  test("fieldOrder: sort overrides dependency protection", () => {
    const src = "class C\n{\n    static int B = A + 1;\n    static int A = 1;\n}\n";
    assert.ok(sortText(src, "a.cs").text.indexOf("int B") < sortText(src, "a.cs").text.indexOf("int A"), "kept by default");
    const forced = sortText(src, "a.cs", { fieldOrder: "sort" }).text;
    assert.ok(forced.indexOf("int A") < forced.indexOf("int B"), "forced");
  });

  test("fieldOrder: preserve keeps every field where it is", () => {
    const src = "class C\n{\n    int z;\n    int a;\n    void M() { }\n}\n";
    const out = sortText(src, "a.cs", { fieldOrder: "preserve" }).text;
    assert.ok(out.indexOf("int z") < out.indexOf("int a"));
  });

  test("names compare case-insensitively", () => {
    const src = "class C\n{\n    public void beta() { }\n    public void Alpha() { }\n    public void alpha2() { }\n}\n";
    assert.deepEqual(csMethods(sortText(src, "a.cs").text), ["Alpha", "alpha2", "beta"]);
  });

  test("overloads keep their relative order", () => {
    const src = "class C\n{\n    public void Run(int b) { }\n    public void Alpha() { }\n    public void Run(string a) { }\n}\n";
    const out = sortText(src, "a.cs").text;
    assert.ok(out.indexOf("Run(int") < out.indexOf("Run(string"));
  });

  test("unbalanced braces: file is left untouched with a warning", () => {
    const r = sortText("class C\n{\n    void B() { \n    void A() { }\n}\n", "a.cs");
    assert.equal(r.changed, false);
    assert.equal(r.hazards[0].code, "syntax-error");
  });

  test("generated files are skipped", () => {
    const r = sortText("// <auto-generated/>\nclass C\n{\n    void B() { }\n    void A() { }\n}\n", "a.cs");
    assert.equal(r.skippedReason, "generated file");
  });

  test("sort-code-disable-file skips the whole file", () => {
    const r = sortText("// sort-code-disable-file\nclass C\n{\n    void B() { }\n    void A() { }\n}\n", "a.cs");
    assert.equal(r.changed, false);
  });

  test("UTF-8 BOM at file start is preserved", () => {
    const r = sortText("\uFEFFclass C\n{\n    void B() { }\n    void A() { }\n}\n", "a.cs");
    assert.ok(r.text.startsWith("\uFEFFclass C"));
    assert.ok(r.text.indexOf("A()") < r.text.indexOf("B()"));
  });
});

describe("TS/JS ordering rules", () => {
  test("exported (public) before non-exported (private)", () => {
    const out = sortText("function a() {}\nexport function z() {}\n", "a.ts").text;
    assert.ok(out.indexOf("function z") < out.indexOf("function a"));
  });

  test("sortTopLevel: false leaves module scope alone but still sorts classes", () => {
    const src = "function b() {}\nfunction a() {}\nclass C {\n  z() {}\n  a() {}\n}\n";
    const out = sortText(src, "a.ts", { typescript: { sortTopLevel: false } }).text;
    assert.ok(out.indexOf("function b") < out.indexOf("function a"));
    assert.ok(out.indexOf("  a()") < out.indexOf("  z()"));
  });

  test("sortClassMembers: false leaves classes alone", () => {
    const src = "class C {\n  z() {}\n  a() {}\n}\n";
    assert.equal(sortText(src, "a.ts", { typescript: { sortClassMembers: false } }).changed, false);
  });

  test("arrow properties as fields when the option is off", () => {
    const src = "class C {\n  run() {}\n  handle = () => 1;\n}\n";
    const asMethod = sortText(src, "a.ts").text;
    const asField = sortText(src, "a.ts", { typescript: { arrowFunctionPropertiesAsMethods: false } }).text;
    assert.ok(asMethod.indexOf("handle") < asMethod.indexOf("run"), "h < r alphabetically among methods");
    assert.ok(asField.indexOf("handle") < asField.indexOf("run"), "fields come before methods");
  });

  test("syntax errors: never touch the file", () => {
    const r = sortText("function b() {\nfunction a() {}\n", "a.ts");
    assert.equal(r.changed, false);
    assert.equal(r.skippedReason, "syntax error");
  });

  test("detachedComments: boundary keeps section comments in place", () => {
    const src = "// == Section ==\n\nfunction b() {}\n\n// == Other ==\n\nfunction z() {}\nfunction a() {}\n";
    const out = sortText(src, "a.ts", { detachedComments: "boundary" }).text;
    assert.ok(out.indexOf("Other") < out.indexOf("function a"));
    assert.ok(out.indexOf("function b") < out.indexOf("Other"));
  });

  test("CRLF files stay CRLF", () => {
    const out = sortText("function b() {}\r\n\r\nfunction a() {}\r\n", "a.ts").text;
    assert.ok(!/[^\r]\n/.test(out));
    assert.ok(out.indexOf("function a") < out.indexOf("function b"));
  });
});

describe("minimalEdit", () => {
  test("replaces only the changed middle", () => {
    assert.deepEqual(minimalEdit("abcXYZdef", "abcZYXdef"), { end: 6, start: 3, text: "ZYX" });
    assert.equal(minimalEdit("same", "same"), null);
  });
});
